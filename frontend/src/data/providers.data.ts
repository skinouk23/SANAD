// ============================================
// HELPER: split a display name into first/last
// ============================================

function splitName(name: string): { firstName: string | null; lastName: string | null } {
  const parts = name.split(' ');
  return {
    firstName: parts[0] ?? null,
    lastName: parts.slice(1).join(' ') || null,
  };
}

function withVerificationDefaults(provider: MockProviderData, index: number): MockProviderData {
  const isVerified = index % 5 !== 1;
  const verificationStatus = isVerified ? ('approved' as const) : ('not_requested' as const);

  return {
    ...provider,
    isVerified,
    verificationConsentGiven: isVerified,
    verificationStatus,
    verificationRequestedAt: isVerified ? provider.createdAt : null,
    verificationReviewedAt: isVerified ? provider.updatedAt : null,
    canRequestVerification: !isVerified,
  };
}

